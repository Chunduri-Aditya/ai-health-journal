#!/usr/bin/env python3
"""Validate the reframe-quality rubric, then optionally score live model output.

Why validation comes first
--------------------------
The obvious move is to point a rubric at the app's reframes and report a score.
That move has already failed twice in this repo: the v1 retrieval gate sat pinned
at 1.000 against a 0.80 floor, and the first crisis numbers were perfect on a set
the author had seen. A metric that cannot go red is not a metric.

So the default run scores a labeled set of hand-written good and bad reframes and
reports whether the rubric SEPARATES them, per failure mode. Only a rubric that
demonstrably discriminates is worth pointing at real output.

Run:
    PYTHONPATH=. python evals/reframe_quality_eval.py
    PYTHONPATH=. python evals/reframe_quality_eval.py --live   # score the real pipeline
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Dict, List

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

os.environ.setdefault("RETRIEVAL_ENABLED", "false")
os.environ.setdefault("VECTOR_BACKEND", "none")

from evals.reframe_quality import score_reframe  # noqa: E402

DEFAULT_CASES = Path(__file__).resolve().parent / "reframe_cases.json"

# The rubric must catch every labeled bad reframe (recall on harm) and must not
# reject good ones. Recall is floored at 1.0 for the same reason crisis
# sensitivity is: the failure modes here are the ones that make a reframe
# actively harmful, so missing one is not a rounding error.
RECALL_FLOOR = float(os.getenv("REFRAME_RECALL_FLOOR", "1.0"))
PRECISION_FLOOR = float(os.getenv("REFRAME_PRECISION_FLOOR", "1.0"))


def _rate(n: int, d: int) -> float:
    return n / d if d else 0.0


def validate(cases: List[dict]) -> int:
    scored = [(c, score_reframe(c["entry"], c["reframe"])) for c in cases]

    good = [(c, s) for c, s in scored if c["label"] == "good"]
    bad = [(c, s) for c, s in scored if c["label"] == "bad"]

    # "positive" = the rubric flags it as unacceptable.
    tp = [(c, s) for c, s in bad if not s.acceptable]
    fn = [(c, s) for c, s in bad if s.acceptable]
    fp = [(c, s) for c, s in good if not s.acceptable]
    tn = [(c, s) for c, s in good if s.acceptable]

    recall = _rate(len(tp), len(tp) + len(fn))
    precision = _rate(len(tp), len(tp) + len(fp))

    print("=== Reframe rubric validation (does it separate good from bad?) ===")
    print(f"  {len(good)} good, {len(bad)} bad reframes\n")
    print(f"  Recall on harmful reframes : {recall:.3f}   <- misses are the costly error")
    print(f"  Precision                  : {precision:.3f}   <- rejecting a good reframe")
    print(f"  Confusion: TP={len(tp)} FN={len(fn)} FP={len(fp)} TN={len(tn)}")

    # Per failure mode, so a headline number cannot hide one blind spot.
    modes: Dict[str, List] = {}
    for c, s in bad:
        modes.setdefault(c.get("failure_mode", "untagged"), []).append((c, s))
    print("\n--- detection rate by failure mode ---")
    for mode, rows in sorted(modes.items()):
        caught = sum(1 for _c, s in rows if not s.acceptable)
        print(f"  {mode:<18} {caught}/{len(rows)}")

    if fn:
        print("\n--- MISSED harmful reframes ---")
        for c, _s in fn:
            print(f"  [{c.get('failure_mode')}] {c['reframe'][:78]!r}")

    if fp:
        print("\n--- GOOD reframes wrongly rejected ---")
        for c, s in fp:
            print(f"  {c['reframe'][:70]!r}")
            for o in s.offenders:
                print(f"     -> {o}")

    print("\n--- grounding overlap (good vs bad) ---")
    g = [s.grounding_overlap for _c, s in good]
    b = [s.grounding_overlap for _c, s in bad]
    print(f"  good: min={min(g):.3f} mean={sum(g)/len(g):.3f}")
    print(f"  bad : min={min(b):.3f} mean={sum(b)/len(b):.3f}")

    passed = recall >= RECALL_FLOOR and precision >= PRECISION_FLOOR
    print(f"\nfloors: recall>={RECALL_FLOOR} precision>={PRECISION_FLOOR}")
    print("PASS" if passed else "FAIL")
    return 0 if passed else 1


def run_live(cases: List[dict]) -> int:
    """Score reframes generated by the real pipeline. Requires Ollama."""
    from app import _run_quality_pipeline
    from model_selection import get_runtime_model_selection
    from config import load_config

    cfg = load_config()
    selection = get_runtime_model_selection(cfg)
    entries = sorted({c["entry"] for c in cases})

    print(f"=== Live reframe scoring ({len(entries)} entries, model={selection.generator}) ===\n")
    results = []
    for entry in entries:
        try:
            analysis = _run_quality_pipeline(
                entry,
                selection.generator,
                verifier_model=selection.verifier,
                fallback_model=selection.fallback,
            )
        except Exception as exc:  # noqa: BLE001 - reported per entry, run continues
            print(f"  [error] {type(exc).__name__} on {entry[:48]!r}")
            continue
        reframe = analysis.get("reframe", "")
        score = score_reframe(entry, reframe)
        results.append((entry, reframe, score))
        state = "ok  " if score.acceptable else "FAIL"
        print(f"  [{state}] {entry[:52]!r}")
        print(f"          {reframe[:100]!r}")
        for o in score.offenders:
            print(f"          -> {o}")

    if not results:
        print("\nNo reframes generated. Is Ollama running?")
        return 1
    ok = sum(1 for _e, _r, s in results if s.acceptable)
    print(f"\n  acceptable: {ok}/{len(results)} ({_rate(ok, len(results)):.3f})")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cases", type=Path, default=DEFAULT_CASES)
    parser.add_argument(
        "--live",
        action="store_true",
        help="generate reframes with the real pipeline and score those (needs Ollama)",
    )
    args = parser.parse_args()

    with args.cases.open(encoding="utf-8") as handle:
        cases = json.load(handle)["cases"]

    if args.live:
        return run_live(cases)
    return validate(cases)


if __name__ == "__main__":
    raise SystemExit(main())
